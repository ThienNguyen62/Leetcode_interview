import java.util.Scanner;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

public class Solution {
    public static boolean solution(String[] board) {
        List<Set<Character>> rows = new ArrayList<>();
        List<Set<Character>> columns = new ArrayList<>();
        List<Set<Character>> boxes = new ArrayList<>();
        for (int i = 0; i < 9; i++) {
            rows.add(new HashSet<>());
            columns.add(new HashSet<>());
            boxes.add(new HashSet<>());
        }

        for (int row = 0; row < 9; row++) {
            for (int col = 0; col < 9; col++) {
                char digit = board[row].charAt(col);
                if (digit == '.') {
                    continue;
                }
                int box = (row / 3) * 3 + col / 3;
                if (!rows.get(row).add(digit) ||
                    !columns.get(col).add(digit) ||
                    !boxes.get(box).add(digit)) {
                    return false;
                }
            }
        }
        return true;
    }

    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        String[] board = new String[9];
        for (int i = 0; i < board.length; i++) {
            board[i] = scanner.next();
        }

        System.out.println(solution(board));
    }
}

