#include <iostream>
#include <string>
#include <unordered_set>
#include <vector>

bool solution(const std::vector<std::string>& board) {
    std::unordered_set<char> rows[9], columns[9], boxes[9];
    for (int row = 0; row < 9; ++row) {
        for (int col = 0; col < 9; ++col) {
            char digit = board[row][col];
            if (digit == '.') {
                continue;
            }
            int box = (row / 3) * 3 + col / 3;
            if (!rows[row].insert(digit).second ||
                !columns[col].insert(digit).second ||
                !boxes[box].insert(digit).second) {
                return false;
            }
        }
    }
    return true;
}

int main() {
    std::vector<std::string> board(9);
    for (auto& row : board) {
        std::cin >> row;
    }

    std::cout << std::boolalpha << solution(board) << '\n';
}

