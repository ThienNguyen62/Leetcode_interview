import sys


def solution(board: list[str]) -> bool:
    rows = [set() for _ in range(9)]
    columns = [set() for _ in range(9)]
    boxes = [set() for _ in range(9)]

    for row, cells in enumerate(board):
        for col, digit in enumerate(cells):
            if digit == ".":
                continue
            box = (row // 3) * 3 + col // 3
            if digit in rows[row] or digit in columns[col] or digit in boxes[box]:
                return False
            rows[row].add(digit)
            columns[col].add(digit)
            boxes[box].add(digit)
    return True


def main() -> None:
    board = sys.stdin.read().split()
    print(str(solution(board)).lower())


if __name__ == "__main__":
    main()


